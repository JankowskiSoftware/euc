#!/usr/bin/env python3
"""Profile an EUC World CSV log and print a Markdown report to stdout.

Usage: python3 -I scripts/profile.py [path/to/sample.csv]
Default path: data/sample.csv (relative to the repo root).
Stdlib only.
"""
import csv
import os
import statistics
import sys
from collections import Counter
from datetime import datetime

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CSV = os.path.join(REPO, "data", "sample.csv")
WHEEL_KEY_COLS = ["speed", "voltage", "current", "current_phase",
                  "safety_margin", "tilt", "roll"]
CUMULATIVE = ["duration", "duration_riding", "distance", "distance_total",
              "energy_consumed", "gps_duration", "gps_duration_riding", "gps_distance"]


def parse_ts(s):
    """Parse EUC World timestamps such as 2026-10-19T12:33:43.219+0200."""
    try:
        return datetime.strptime(s, "%Y-%m-%dT%H:%M:%S.%f%z")
    except ValueError:
        return datetime.fromisoformat(s)


def to_float(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def pct(part, whole):
    return 100.0 * part / whole if whole else 0.0


def fmt(x):
    if x is None:
        return "-"
    if isinstance(x, float):
        if x != x:
            return "-"
        return f"{x:.4g}" if abs(x) < 1e6 else f"{x:.6g}"
    return str(x)


def p95(values):
    v = sorted(values)
    return v[min(len(v) - 1, int(round(0.95 * (len(v) - 1))))] if v else None


def fmt_secs(x):
    return "-" if x is None else f"{x:.3f} s"


def load(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = [r for r in reader if r]
    return header, rows


def main(path):
    header, rows = load(path)
    idx = {name: i for i, name in enumerate(header)}
    n = len(rows)
    out = []
    w = out.append

    w(f"# Data profile: `{os.path.relpath(path, REPO)}`")
    w("")
    w("Generated by `scripts/profile.py`. Raw rows are the CSV data rows (header excluded).")
    w("")

    def col(name):
        i = idx[name]
        return [r[i] if i < len(r) else "" for r in rows]

    # Time span
    dts = [parse_ts(v) for v in col("datetime") if v]
    gps_raw = [v for v in col("gps_datetime") if v]
    span = (dts[-1] - dts[0]).total_seconds() if dts else 0.0
    w("## Time span")
    w("")
    w(f"- Raw rows: **{n}** (columns: {len(header)})")
    w(f"- First datetime: `{dts[0].isoformat()}`")
    w(f"- Last datetime: `{dts[-1].isoformat()}`")
    w(f"- Span: **{span:.1f} s** ({span / 60:.1f} min)")
    w("")

    # Sampling of raw rows
    raw_deltas = [(b - a).total_seconds() for a, b in zip(dts, dts[1:])]
    w("## Raw row sampling")
    w("")
    w(f"- Datetime delta median: **{fmt_secs(statistics.median(raw_deltas) if raw_deltas else None)}**")
    w(f"- Datetime delta p95: **{fmt_secs(p95(raw_deltas))}**")
    w(f"- Non-monotonic steps (delta <= 0): {sum(1 for d in raw_deltas if d <= 0)}")
    w("")

    # Wheel samples: runs of identical key across consecutive raw rows
    wheel_idx = [idx[c] for c in WHEEL_KEY_COLS]
    runs = []  # list of [start_ts, count]
    prev = None
    for r, ts in zip(rows, dts):
        key = tuple(r[i] if i < len(r) else "" for i in wheel_idx)
        if key != prev:
            runs.append([ts, 1])
            prev = key
        else:
            runs[-1][1] += 1
    wheel_periods = [(b[0] - a[0]).total_seconds() for a, b in zip(runs, runs[1:])]
    dup_dist = Counter(c for _, c in runs)
    w("## Wheel samples (deduplicated)")
    w("")
    w(f"Key: `{', '.join(WHEEL_KEY_COLS)}`; a sample is a run of consecutive raw rows with an identical key.")
    w("")
    w(f"- Wheel-sample count: **{len(runs)}**")
    w(f"- Median period between sample starts: **{fmt_secs(statistics.median(wheel_periods) if wheel_periods else None)}**")
    w(f"- p95 period: **{fmt_secs(p95(wheel_periods))}**")
    w(f"- Raw rows per sample: median {statistics.median(c for _, c in runs):g}, "
      f"min {min(c for _, c in runs)}, max {max(c for _, c in runs)}")
    w("")
    w("Duplicates per wheel sample (rows per sample -> number of samples):")
    w("")
    w("| Rows per sample | Samples | Share |")
    w("|---:|---:|---:|")
    for k in sorted(dup_dist):
        w(f"| {k} | {dup_dist[k]} | {pct(dup_dist[k], len(runs)):.1f}% |")
    w("")

    # GPS samples: deduplicate by gps_datetime
    gps_unique = list(dict.fromkeys(gps_raw))
    gps_ts = [parse_ts(v) for v in gps_unique]
    gps_periods = [(b - a).total_seconds() for a, b in zip(gps_ts, gps_ts[1:])]
    w("## GPS samples (deduplicated by `gps_datetime`)")
    w("")
    w(f"- Rows with `gps_datetime`: {len(gps_raw)}")
    w(f"- GPS-sample count after dedup: **{len(gps_unique)}**")
    w(f"- Median period: **{fmt_secs(statistics.median(gps_periods) if gps_periods else None)}**; "
      f"p95: **{fmt_secs(p95(gps_periods))}**")
    if gps_ts:
        w(f"- GPS span: `{gps_ts[0].isoformat()}` to `{gps_ts[-1].isoformat()}`")
    w("")

    # Column fill rates and numeric stats
    w("## Columns")
    w("")
    w("| # | Column | Fill % | Type | Min | Median | Max |")
    w("|---:|---|---:|---|---:|---:|---:|")
    for i, name in enumerate(header):
        vals = col(name)
        filled = [v for v in vals if v != ""]
        fill = pct(len(filled), n)
        nums = [to_float(v) for v in filled]
        if filled and all(x is not None for x in nums):
            kind = "numeric"
            mn, md, mx = min(nums), statistics.median(nums), max(nums)
            w(f"| {i} | `{name}` | {fill:.1f} | {kind} | {fmt(mn)} | {fmt(md)} | {fmt(mx)} |")
        elif filled:
            w(f"| {i} | `{name}` | {fill:.1f} | text | - | - | - |")
        else:
            w(f"| {i} | `{name}` | 0.0 | empty | - | - | - |")
    w("")
    w("Cumulative columns (`" + "`, `".join(CUMULATIVE) + "`) should be monotonic; "
      "checked on raw rows:")
    w("")
    for name in CUMULATIVE:
        nums = [to_float(v) for v in col(name)]
        nums = [x for x in nums if x is not None]
        drops = sum(1 for a, b in zip(nums, nums[1:]) if b < a)
        w(f"- `{name}`: decreasing steps = {drops}")
    w("")

    # Alarm counts on raw rows
    alarm_counts = Counter(v if v else "(empty)" for v in col("alarm"))
    w("## Alarm values (raw rows)")
    w("")
    w("| Value | Binary | Rows | Share |")
    w("|---:|---:|---:|---:|")
    for val, c in sorted(alarm_counts.items(), key=lambda kv: -kv[1]):
        bits = bin(int(val))[2:] if val.isdigit() else "-"
        w(f"| {val} | {bits} | {c} | {pct(c, n):.2f}% |")
    w("")

    # Extra metadata
    extra_pairs = []
    for ri, v in enumerate(col("extra")):
        if not v:
            continue
        for part in v.split(";"):
            part = part.strip()
            if not part:
                continue
            k, _, val = part.partition("=")
            extra_pairs.append((ri, k.strip(), val.strip()))
    w("## Extra metadata (`extra` column)")
    w("")
    w(f"Rows with `extra`: {sum(1 for v in col('extra') if v)}; key=value pairs: {len(extra_pairs)}")
    w("")
    w(f"Raw rows {min(ri for ri, _, _ in extra_pairs)}-{max(ri for ri, _, _ in extra_pairs)} "
      "carry the metadata (one pair per row, in file order):")
    w("")
    items = [f"`{k}={val}`" for _, k, val in extra_pairs]
    for j in range(0, len(items), 3):
        w("- " + " · ".join(items[j:j + 3]))
    w("")
    return "\n".join(out)


if __name__ == "__main__":
    csv_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CSV
    sys.stdout.write(main(csv_path) + "\n")
